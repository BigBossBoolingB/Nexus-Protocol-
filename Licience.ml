# NNexus Protocol - Sovereign Software License (Draft)

This document outlines the principles of the license governing the Nexus Protocol software and its components. This is not a formal legal document but a declaration of intent to be codified by legal counsel.

## Core Principle: Architectural Sovereignty

The Nexus Protocol is architected to be a sovereign, self-sustaining digital nation. The right to use, modify, and operate the software is intrinsically linked to active, good-faith participation in this nation. This license is designed to protect the network's sovereignty from all forms of colonization, whether by centralized corporations or by non-contributing, parasitic actors.

## Grant of Rights

A license to operate the Nexus Protocol software is granted to any entity ("Citizen") under the following conditions:

1.  **Participation:** The Citizen must operate a node (either a Sentinel or a Nomad) that is actively and verifiably participating in the network's consensus and data propagation according to the Proof of Architecture protocol.
2.  **Good Faith:** The Citizen's node must operate in good faith, not acting to disrupt, censor, or degrade the network.
3.  **No Re-appropriation:** The Citizen may not use the core source code of the Nexus Protocol to create a competing, separate network that does not connect to and participate in the primary Nexus Protocol network. The software's purpose is to build a single, unified, sovereign network, not to be a template for fractured, independent systems.

## Termination

The right to operate the software is automatically revoked if a Citizen ceases to be an active, good-faith participant in the network, as determined by the mechanisms of the Proof of Architecture protocol and, in extreme cases, by a vote of the Nexus DAO.

